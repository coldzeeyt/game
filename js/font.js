function textWidth(text, scale = 1) {
  const n = String(text).length;
  return n ? (n * 6 - 1) * scale : 0;
}

function drawText(ctx, text, x, y, color, scale = 1, align = 'left') {
  text = String(text);
  const w = textWidth(text, scale);
  if (align === 'center') x -= Math.floor(w / 2);
  else if (align === 'right') x -= w;
  x = Math.round(x);
  y = Math.round(y);
  ctx.fillStyle = color;
  for (const ch of text) {
    const g = FONT[ch] || FONT[ch.toUpperCase()];
    if (g) {
      for (let r = 0; r < 7; r++) {
        for (let c = 0; c < 5; c++) {
          if ((g[r] >> (4 - c)) & 1) ctx.fillRect(x + c * scale, y + r * scale, scale, scale);
        }
      }
    }
    x += 6 * scale;
  }
}

// Text with a 1-pixel (scaled) black outline so it reads on any background.
function drawTextOutlined(ctx, text, x, y, color, scale = 1, align = 'left', outline = '#000000') {
  for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) {
    drawText(ctx, text, x + dx * scale, y + dy * scale, outline, scale, align);
  }
  drawText(ctx, text, x, y, color, scale, align);
}

// Tiny 3x5 font, used for small print like the ColdzeeYT credit.
const TINY_FONT = (() => {
  const src = {
    C: '011 100 100 100 011', o: '000 010 101 101 010', l: '110 010 010 010 111',
    d: '001 001 011 101 011', z: '000 111 001 010 111', e: '000 011 111 100 011',
    Y: '101 101 010 010 010', T: '111 010 010 010 010',
  };
  const glyphs = {};
  for (const ch in src) glyphs[ch] = src[ch].split(' ').map((r) => parseInt(r, 2));
  return glyphs;
})();

function drawTinyText(ctx, text, x, y, color) {
  x = Math.round(x - (text.length * 4 - 1) / 2); // centered
  ctx.fillStyle = color;
  for (const ch of text) {
    const g = TINY_FONT[ch];
    if (g) for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) if ((g[r] >> (2 - c)) & 1) ctx.fillRect(x + c, y + r, 1, 1);
    x += 4;
  }
}
